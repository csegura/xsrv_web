"""Writes THIRD-PARTY-NOTICES.txt: the crates in Cargo.lock with their declared licenses.

Run it from the repository root after a dependency change: python3 tools/third-party-notices.py
"""
import json
import subprocess
import sys

HEADER = """Third-party software in xsrv-web
================================

xsrv-web is free software under the GNU Affero General Public License, version 3 (see LICENSE).
The Rust crates below are those in Cargo.lock (those for another platform are not compiled in). Each one is under the license that its authors declare,
shown here as an SPDX expression; a crate with "OR" may be used under any of the alternatives.
The text of each license is in the source package of the crate (https://crates.io/crates/<name>).
Each crate is under at least one license that is compatible with the AGPL v3 (MIT, Apache-2.0,
BSD-2-Clause, BSD-3-Clause, BSL-1.0, Unlicense, Unicode-3.0).

Generated by tools/third-party-notices.py from Cargo.lock; do not edit by hand.

"""


def main():
    metadata = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--locked"],
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    )
    own = set(metadata["workspace_members"])
    rows = sorted(
        (p["name"], p["version"], p.get("license") or "see the crate", p.get("repository") or "")
        for p in metadata["packages"]
        if p["id"] not in own
    )
    missing = [row[0] for row in rows if row[2] == "see the crate"]
    if missing:
        sys.exit(f"no license declared for: {', '.join(missing)}")
    with open("THIRD-PARTY-NOTICES.txt", "w", encoding="utf-8") as out:
        out.write(HEADER)
        for name, version, license_id, repository in rows:
            out.write(f"{name} {version}\n  license: {license_id}\n")
            if repository:
                out.write(f"  source: {repository}\n")
    print(f"{len(rows)} crates")


main()
